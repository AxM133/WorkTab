/** Документ в виде обычного текста — для кнопки «Скачать документ» */
export function legalDocToText(doc) {
  const lines = [`WorkTap — ${doc.title}`, `Редакция от ${doc.updatedAt}`, '', doc.heading.toUpperCase(), '']

  for (const section of doc.sections) {
    lines.push(section.title, '')
    for (const block of section.blocks) {
      if (typeof block === 'string') lines.push(block)
      else if (block.list) lines.push(...block.list.map((item) => `• ${item}`))
      else lines.push(...block.ordered.map((item, index) => `${(block.start ?? 1) + index}. ${item}`))
      lines.push('')
    }
  }

  return lines.join('\n')
}
